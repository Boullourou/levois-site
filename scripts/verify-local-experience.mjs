import { chromium } from '@playwright/test';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

// Reproducible UI fixture: actual DVF record coordinates and address, mocked BAN
// response. No live geocoding, email, lead API or external mutation is performed.
const base = process.env.LEVOIS_TEST_URL || 'http://127.0.0.1:4331';
const output = 'docs/design/cible-20260910/preuves';
await mkdir(output, { recursive: true });
const dataset = JSON.parse(await readFile('public/data/dvf-secteur.json', 'utf8'));
const transaction = dataset.find(item => item.co === 'Lèves' && item.vo && item.t === 'Maison');
assert.ok(transaction, 'A real Lèves address is needed for the UI fixture.');
const address = [transaction.no, transaction.vo, transaction.cp, transaction.co].filter(Boolean).join(' ');
const feature = { type: 'Feature', geometry: { type: 'Point', coordinates: [transaction.lon, transaction.lat] }, properties: { label: address, postcode: transaction.cp, city: transaction.co, citycode: '28000' } };
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
await context.route('https://data.geopf.fr/geocodage/search*', route => route.fulfill({ json: { type: 'FeatureCollection', features: [feature, { ...feature, properties: { ...feature.properties, label: 'Autre proposition de test — confirmer avant lecture' } }] } }));
await context.addInitScript(() => { document.addEventListener('DOMContentLoaded',()=>{const style=document.createElement('style');style.textContent='astro-dev-toolbar{display:none!important}';document.head.append(style);}); });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const response = await page.goto(`${base}/votre-rue?q=${encodeURIComponent(address)}`, { waitUntil: 'networkidle' });
assert.equal(response.status(), 200);
assert.equal(await page.locator('#vr-form').evaluate(element=>getComputedStyle(element).position),'static','The search must remain in normal document flow.');
await page.locator('#vr-suggestions li').first().waitFor({ state: 'visible' });
assert.equal(await page.locator('#vr-scene').isVisible(), false, 'An ambiguous address must not automatically show results.');
await page.screenshot({ path: `${output}/local-mobile-390-entree.png`, fullPage: true });
await page.locator('#vr-suggestions li').first().click();
await page.locator('#vr-conv').waitFor({ state: 'visible', timeout: 20000 });
assert.ok(await page.locator('.vr-results').textContent().then(value => value.includes('2021–2025')));
await page.locator('[data-path="lecture"]').click();
await page.locator('[data-local-answer="buyer"]').click();
await page.locator('[data-local-answer="budget"]').click();
await page.locator('.vr-local-reading').waitFor({ state: 'visible' });
assert.ok((await page.locator('.vr-local-reading').textContent()).includes('coût complet'));
assert.equal(await page.locator('input[type="email"],input[type="tel"],#vr-lead').count(), 0);
const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('levois:experience:v1')));
assert.equal(saved.project, 'local');
assert.equal(saved.answers.local_intention.value, 'buyer');
assert.equal(saved.entry.door, 'unknown');
assert.equal(saved.answers.seller_situation, undefined);
assert.equal(saved.reading.sections.length, 4);
const reflow = async () => page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }));
assert.ok((await reflow()).document <= 390, 'Mobile page must not overflow horizontally.');
await page.screenshot({ path: `${output}/local-mobile-390-lecture.png`, fullPage: true });
await page.locator('.vr-local-reading a[href="/lecture"]').click();
await page.waitForURL('**/lecture');
await page.locator('body').filter({ hasText: 'Vos repères locaux' }).waitFor();
await page.screenshot({ path: `${output}/local-mobile-390-restitution-commune.png`, fullPage: true });

await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto(`${base}/votre-rue?q=${encodeURIComponent(address)}&confirmee=1`, { waitUntil: 'networkidle' });
await page.locator('#vr-conv').waitFor({ state: 'visible' });
await page.locator('[data-path="lecture"]').click();
await page.locator('.vr-local-reading').waitFor({ state: 'visible' });
await page.screenshot({ path: `${output}/local-desktop-1440-lecture.png`, fullPage: true });
assert.ok((await reflow()).document <= 1440, 'Desktop page must not overflow horizontally.');

await page.setViewportSize({ width: 320, height: 800 });
await page.goto(`${base}/votre-rue`, { waitUntil: 'networkidle' });
assert.ok((await reflow()).document <= 320, '320 px page must not overflow horizontally.');
await page.screenshot({ path: `${output}/local-mobile-320-entree.png`, fullPage: true });
await context.route('**/data/dvf-secteur.json', route => route.fulfill({ status: 503, body: 'Test: unavailable DVF' }));
await page.locator('#vr-adresse').fill(address);
await page.locator('#vr-form button[type="submit"]').click();
await page.locator('#vr-conv').waitFor({ state: 'visible' });
assert.ok((await page.locator('#vr-scene').textContent()).includes('pas disponibles'));
await page.locator('[data-path="lecture"]').click();
await page.locator('.vr-local-reading,[data-local-answer]').first().waitFor({ state: 'visible' });
if (await page.locator('[data-local-answer="budget"]').count()) await page.locator('[data-local-answer="budget"]').click();
await page.screenshot({ path: `${output}/local-mobile-320-donnees-indisponibles.png`, fullPage: true });
assert.deepEqual(errors, []);
const result = { status: 'passed', browser: 'Chromium', viewports: [320, 390, 1440], errors, geocoding: 'Mocked response from an actual DVF record; ambiguity and q/confirmee compatibility tested.', data: 'Actual repository DVF dataset; unavailable response tested separately.', checks: ['Value before contact', 'Two-question personal reading', 'No implicit seller/QR classification', 'Shared reading continuity', 'No horizontal overflow', 'DVF failure retains autonomous reading'], screenshots: 6 };
await writeFile(`${output}/local-ui-verification.json`, JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
await browser.close();
